/// M10's tables of `docs/perf/halo-exchange.md` from the `m10-halo-*.json` records (the last
/// record of a part wins): per (target, backend, type, ranks) the median of each part in µs at
/// each halo size, then one row per platform at 10^5 nodes,
/// `| target backend | type | ranks | d2h µs | h2d µs | h2d / d2h | reverse / forward | bound | cause |`.
pub fn render_m10_halo(records: &[crate::record::HaloRecord]) -> String {
    type Key = (String, String, &'static str, usize);
    let mut medians: BTreeMap<Key, BTreeMap<(usize, &str), f64>> = BTreeMap::new();
    let mut about: BTreeMap<Key, (String, String)> = BTreeMap::new();
    for r in records {
        let key = (
            r.target.clone(),
            r.backend.clone(),
            r.scalar.name(),
            r.ranks,
        );
        let part = crate::record::HALO_PARTS
            .iter()
            .find(|p| **p == r.part)
            .copied()
            .unwrap_or("?");
        medians
            .entry(key.clone())
            .or_default()
            .insert((r.halo_nodes, part), r.median_s);
        let commit: String = r.commit.chars().take(12).collect();
        about.insert(key, (r.device.clone(), commit));
    }
    let us = |t: Option<&f64>| t.map_or("–".to_owned(), |t| format!("{:.1}", t * 1e6));
    let mut out = String::new();
    for (key, times) in &medians {
        let (target, backend, scalar, ranks) = key;
        let (device, commit) = &about[key];
        let halos: BTreeSet<usize> = times.keys().map(|(h, _)| *h).collect();
        let _ = writeln!(
            out,
            "**{target} {backend}, {scalar}, {ranks} rank{}** ({device}; commit {commit}). \
             Median µs:\n",
            if *ranks == 1 { "" } else { "s" }
        );
        let heads: String = halos.iter().map(|h| format!(" {h} |")).collect();
        let rules: String = halos.iter().map(|_| " ---: |").collect();
        let _ = writeln!(out, "| part |{heads}\n| --- |{rules}");
        for part in crate::record::HALO_PARTS {
            if !times.keys().any(|(_, p)| *p == part) {
                continue;
            }
            let cells: String = halos
                .iter()
                .map(|h| format!(" {} |", us(times.get(&(*h, part)))))
                .collect();
            let _ = writeln!(out, "| {part} |{cells}");
        }
        out.push('\n');
    }
    let _ = writeln!(
        out,
        "At {HALO_BOUND_NODES} halo nodes:\n\n\
         | target backend | type | ranks | d2h µs | h2d µs | h2d / d2h | reverse / forward | \
         bound | cause |\n\
         | --- | --- | ---: | ---: | ---: | ---: | ---: | --- | --- |"
    );
    for (key, times) in &medians {
        let (target, backend, scalar, ranks) = key;
        let at = |part| times.get(&(HALO_BOUND_NODES, part)).copied();
        let ratio = |a: Option<f64>, b: Option<f64>| a.zip(b).map(|(a, b)| a / b);
        let fmt = |r: Option<f64>| r.map_or("–".to_owned(), |r| format!("{r:.2}"));
        let h2d = ratio(at("h2d"), at("d2h"));
        let rev = ratio(at("reverse"), at("forward"));
        let cpu = backend == "cpu";
        let shared_gpu = backend == "cuda" && *ranks > 1;
        let bound = if cpu || shared_gpu {
            format!("reverse ≤ {REVERSE_BOUND} × forward; h2d reported")
        } else {
            format!("h2d ≤ {H2D_BOUND} × d2h; reverse ≤ {REVERSE_BOUND} × forward")
        };
        let mut causes = Vec::new();
        if cpu {
            causes.push(CPU_H2D_CAUSE.to_owned());
        } else if shared_gpu {
            causes.push(SHARED_GPU_H2D_CAUSE.to_owned());
        } else if h2d.is_some_and(|r| r > H2D_BOUND) {
            causes.push("h2d over the bound".to_owned());
        }
        if rev.is_some_and(|r| r > REVERSE_BOUND) {
            causes.push("reverse over the bound".to_owned());
        }
        let cause = if causes.is_empty() {
            "–".to_owned()
        } else {
            causes.join("; ")
        };
        let _ = writeln!(
            out,
            "| {target} {backend} | {scalar} | {ranks} | {} | {} | {} | {} | {bound} | {cause} |",
            us(at("d2h").as_ref()),
            us(at("h2d").as_ref()),
            fmt(h2d),
            fmt(rev),
        );
    }
    out
}

/// The scalar types of the report's rows for `kind`: the sweep's, or f32 and f64 for the
/// families without a kernel yet (Pack, PullBack).
fn row_scalars(kind: KernelKind) -> Vec<Scalar> {
    let scalars = scalars_of(kind);
    if scalars.is_empty() {
        vec![Scalar::F32, Scalar::F64]
    } else {
        scalars
    }
}

/// Vector sizes above 1.
fn wide_sizes() -> Vec<usize> {
    (1..=VECTOR_PAD.ilog2()).map(|k| 1 << k).collect()
}

/// `a / b`: the speedup of size `v` at each rule size, `–` where not measured; ` (ran m)` if
/// the size ran narrower everywhere.
fn speedups(times: &[BTreeMap<Config, Timing>; 2], v: usize) -> String {
    let s: Vec<Option<f64>> = times.iter().map(|t| speedup(t, v)).collect();
    if s.iter().all(Option::is_none) {
        return "–".to_owned();
    }
    let cells: Vec<String> = s
        .iter()
        .map(|s| s.map_or("–".to_owned(), |s| format!("{s:.2}")))
        .collect();
    let ran = times[0]
        .iter()
        .filter(|((n, ..), _)| *n == v)
        .map(|(_, t)| t.ran)
        .max();
    match ran {
        Some(ran) if ran < v => format!("{} (ran {ran})", cells.join(" / ")),
        _ => cells.join(" / "),
    }
}

fn block(units: Option<usize>) -> String {
    units.map_or("–".to_owned(), |u| {
        format!("{} KiB", (u * BLOCK_UNIT) >> 10)
    })
}

fn units(units: Option<CpuUnits>) -> &'static str {
    units.map_or("–", units_name)
}

/// The generated tables, without the markers.
pub fn render(data: &PerfData, decision: &Decision) -> String {
    let wide = wide_sizes();
    let size_heads: String = wide.iter().map(|v| format!(" {v} |")).collect();
    let size_rule: String = wide.iter().map(|_| " ---: |").collect();
    let mut out = String::new();

    out.push_str(
        "### Vector sizes\n\n\
         Speedup of each vector size over size 1 at 10^6 / 10^7 items: the best time over tiles \
         blocks and CPU units at size 1 over the best at that size; for a class measured on \
         several devices, the geometric mean of the per-device ratios (ADR-0015). \"(ran m)\": \
         every device ran the size at m lanes. Size, tile, block and units are the entries of \
         `vector-policy.toml`; f32 and u32 share the 4-byte entries. Units: all hardware \
         threads or the performance cores; a device without a performance-core count gives \
         both the same time (ADR-0017). A reason \"closest, x% slower\" marks an entry where no \
         admitted configuration is within 3% of the fastest at both sizes, so the rule took the \
         one with the smallest worst-case ratio, at most 10% slower (ADR-0018); \"closest \
         across types\" marks a shared 4-byte entry whose types disagree, at most 25% slower \
         (ADR-0021); \"unresolved\" marks one where even that bound is exceeded.\n\n",
    );
    writeln!(
        out,
        "| Family | Class | Type |{size_heads} Size | Tile | Block | Units | Reason |"
    )
    .unwrap();
    writeln!(
        out,
        "| --- | --- | --- |{size_rule} ---: | ---: | ---: | --- | --- |"
    )
    .unwrap();
    for kind in KINDS.into_iter().filter(|&k| k != KernelKind::Scalar) {
        for class in LegacyClass::ALL {
            for scalar in row_scalars(kind) {
                let bytes = scalar.bytes();
                let times = RULE_SIZES.map(|n| class_times(data, class, kind, scalar, n));
                let cells: String = wide
                    .iter()
                    .map(|&v| format!(" {} |", speedups(&times, v)))
                    .collect();
                let choice = decision.choice(class, kind, bytes);
                let tile = if kind == KernelKind::GeomFactors {
                    decision.quad_tile(class, bytes).to_string()
                } else {
                    "–".to_owned()
                };
                writeln!(
                    out,
                    "| {kind:?} | {class:?} | {} |{cells} {} | {tile} | {} | {} | {} |",
                    scalar.name(),
                    choice.map_or(1, |c| c.vector_size),
                    block(choice.and_then(|c| c.cpu_block)),
                    units(choice.and_then(|c| c.cpu_units)),
                    choice.map_or("", |c| c.reason.as_str()),
                )
                .unwrap();
            }
        }
    }

    out.push_str(
        "\n### Per device\n\n\
         The speedups of each measured device, at 10^6 / 10^7 items.\n\n",
    );
    writeln!(out, "| Family | Type | Class | Device |{size_heads}").unwrap();
    writeln!(out, "| --- | --- | --- | --- |{size_rule}").unwrap();
    for kind in KINDS.into_iter().filter(|&k| k != KernelKind::Scalar) {
        for scalar in row_scalars(kind) {
            for class in LegacyClass::ALL {
                let per_size = RULE_SIZES.map(|n| device_times(data, class, kind, scalar, n));
                for device in per_size[0].keys() {
                    let times =
                        [0, 1].map(|i| per_size[i].get(device).cloned().unwrap_or_default());
                    let cells: String = wide
                        .iter()
                        .map(|&v| format!(" {} |", speedups(&times, v)))
                        .collect();
                    let name = data
                        .sweeps
                        .iter()
                        .find(|r| (&r.target, &r.backend) == (&device.0, &device.1))
                        .map_or("", |r| r.device.as_str());
                    writeln!(
                        out,
                        "| {kind:?} | {} | {class:?} | {} {} ({name}) |{cells}",
                        scalar.name(),
                        device.0,
                        device.1
                    )
                    .unwrap();
                }
            }
        }
    }

    out.push_str(
        "\n### Scalar kernels\n\n\
         CPU blocks and units of `KernelKind::Scalar` (vector size 1), from histogram (u32) and \
         segmented reduce (f64) (ADR-0015, item 7; ADR-0017).\n\n",
    );
    out.push_str("| Class | Type | Block | Units | Reason |\n| --- | --- | ---: | --- | --- |\n");
    for class in LegacyClass::ALL
        .into_iter()
        .filter(|&c| c != LegacyClass::Gpu)
    {
        for scalar in scalars_of(KernelKind::Scalar) {
            let choice = decision.choice(class, KernelKind::Scalar, scalar.bytes());
            writeln!(
                out,
                "| {class:?} | {} | {} | {} | {} |",
                scalar.name(),
                block(choice.and_then(|c| c.cpu_block)),
                units(choice.and_then(|c| c.cpu_units)),
                choice.map_or("", |c| c.reason.as_str()),
            )
            .unwrap();
        }
    }
    out
}

/// `text` with the part between the markers replaced by `generated`; the markers are appended
/// if `text` has none.
///
/// # Errors
///
/// If `text` has a begin marker without an end marker after it.
pub fn splice(text: &str, generated: &str) -> Result<String, String> {
    let block = format!("{BEGIN_MARKER}\n\n{}\n\n{END_MARKER}", generated.trim());
    let Some(begin) = text.find(BEGIN_MARKER) else {
        let sep = if text.is_empty() || text.ends_with("\n\n") {
            ""
        } else if text.ends_with('\n') {
            "\n"
        } else {
            "\n\n"
        };
        return Ok(format!("{text}{sep}{block}\n"));
    };
    let end = text[begin..]
        .find(END_MARKER)
        .ok_or("a BEGIN GENERATED marker without END GENERATED")?
        + begin
        + END_MARKER.len();
    Ok(format!("{}{block}{}", &text[..begin], &text[end..]))
}

/// `text` with the part between [`M10_BEGIN_MARKER`] and [`M10_END_MARKER`] replaced by
/// `generated`.
///
/// # Errors
///
/// If `text` lacks either marker, or has them out of order.
pub fn splice_m10(text: &str, generated: &str) -> Result<String, String> {
    splice_between(text, M10_BEGIN_MARKER, M10_END_MARKER, "M10", generated)
}

/// `text` with the part between [`M10C_BEGIN_MARKER`] and [`M10C_END_MARKER`] replaced by
/// `generated`.
///
/// # Errors
///
/// If `text` lacks either marker, or has them out of order.
pub fn splice_m10c(text: &str, generated: &str) -> Result<String, String> {
    splice_between(text, M10C_BEGIN_MARKER, M10C_END_MARKER, "M10c", generated)
}

fn splice_between(
    text: &str,
    begin_marker: &str,
    end_marker: &str,
    what: &str,
    generated: &str,
) -> Result<String, String> {
    let begin = text
        .find(begin_marker)
        .ok_or_else(|| format!("no {what} BEGIN GENERATED marker"))?;
    let end = text[begin..]
        .find(end_marker)
        .ok_or_else(|| format!("an {what} BEGIN GENERATED marker without END GENERATED {what}"))?
        + begin;
    Ok(format!(
        "{}{begin_marker}\n\n{}\n\n{}",
        &text[..begin],
        generated.trim(),
        &text[end..]
    ))
}

