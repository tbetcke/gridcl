//! The generated tables of `docs/perf/vectorization.md`: for every candidate family, device
//! class and scalar type, the speedup of each vector size over size 1, the chosen size and the
//! reason; the same speedups per device (ADR-0015, item 5); and the CPU blocks of the scalar
//! kernels.

use std::collections::BTreeMap;
use std::fmt::Write;

use gridcl_device::{DeviceClass, KernelKind, VECTOR_PAD};

use crate::decide::{
    BLOCK_UNIT, Config, Decision, RULE_SIZES, Timing, class_times, device_times, scalars_of,
    speedup,
};
use crate::record::{CLASSES, KINDS, PerfData, Scalar};

/// The line before the generated tables in `docs/perf/vectorization.md`.
pub const BEGIN_MARKER: &str = "<!-- BEGIN GENERATED by policy_report; do not edit -->";
/// The line after the generated tables.
pub const END_MARKER: &str = "<!-- END GENERATED -->";

/// The scalar types of the report's rows for `kind`: the sweep's, or f32 and f64 for the
/// families without a kernel yet (Pack, PullBack).
fn row_scalars(kind: KernelKind) -> Vec<Scalar> {
    let scalars = scalars_of(kind);
    if scalars.is_empty() {
        vec![Scalar::F32, Scalar::F64]
    } else {
        scalars
    }
}

/// Vector sizes above 1.
fn wide_sizes() -> Vec<usize> {
    (1..=VECTOR_PAD.ilog2()).map(|k| 1 << k).collect()
}

/// `a / b`: the speedup of size `v` at each rule size, `–` where not measured; ` (ran m)` if
/// the size ran narrower everywhere.
fn speedups(times: &[BTreeMap<Config, Timing>; 2], v: usize) -> String {
    let s: Vec<Option<f64>> = times.iter().map(|t| speedup(t, v)).collect();
    if s.iter().all(Option::is_none) {
        return "–".to_owned();
    }
    let cells: Vec<String> = s
        .iter()
        .map(|s| s.map_or("–".to_owned(), |s| format!("{s:.2}")))
        .collect();
    let ran = times[0]
        .iter()
        .filter(|((n, _, _), _)| *n == v)
        .map(|(_, t)| t.ran)
        .max();
    match ran {
        Some(ran) if ran < v => format!("{} (ran {ran})", cells.join(" / ")),
        _ => cells.join(" / "),
    }
}

fn block(units: Option<usize>) -> String {
    units.map_or("–".to_owned(), |u| {
        format!("{} KiB", (u * BLOCK_UNIT) >> 10)
    })
}

/// The generated tables, without the markers.
pub fn render(data: &PerfData, decision: &Decision) -> String {
    let wide = wide_sizes();
    let size_heads: String = wide.iter().map(|v| format!(" {v} |")).collect();
    let size_rule: String = wide.iter().map(|_| " ---: |").collect();
    let mut out = String::new();

    out.push_str(
        "### Vector sizes\n\n\
         Speedup of each vector size over size 1 at 10^6 / 10^7 items: the best time over tiles \
         and blocks at size 1 over the best at that size; for a class measured on several \
         devices, the geometric mean of the per-device ratios (ADR-0015). \"(ran m)\": every \
         device ran the size at m lanes. Size, tile and block are the entries of \
         `vector-policy.toml`; f32 and u32 share the 4-byte entries.\n\n",
    );
    writeln!(
        out,
        "| Family | Class | Type |{size_heads} Size | Tile | Block | Reason |"
    )
    .unwrap();
    writeln!(
        out,
        "| --- | --- | --- |{size_rule} ---: | ---: | ---: | --- |"
    )
    .unwrap();
    for kind in KINDS.into_iter().filter(|&k| k != KernelKind::Scalar) {
        for class in CLASSES {
            for scalar in row_scalars(kind) {
                let bytes = scalar.bytes();
                let times = RULE_SIZES.map(|n| class_times(data, class, kind, scalar, n));
                let cells: String = wide
                    .iter()
                    .map(|&v| format!(" {} |", speedups(&times, v)))
                    .collect();
                let choice = decision.choice(class, kind, bytes);
                let tile = if kind == KernelKind::GeomFactors {
                    decision.quad_tile(class, bytes).to_string()
                } else {
                    "–".to_owned()
                };
                writeln!(
                    out,
                    "| {kind:?} | {class:?} | {} |{cells} {} | {tile} | {} | {} |",
                    scalar.name(),
                    choice.map_or(1, |c| c.vector_size),
                    block(choice.and_then(|c| c.cpu_block)),
                    choice.map_or("", |c| c.reason.as_str()),
                )
                .unwrap();
            }
        }
    }

    out.push_str(
        "\n### Per device\n\n\
         The speedups of each measured device, at 10^6 / 10^7 items.\n\n",
    );
    writeln!(out, "| Family | Type | Class | Device |{size_heads}").unwrap();
    writeln!(out, "| --- | --- | --- | --- |{size_rule}").unwrap();
    for kind in KINDS.into_iter().filter(|&k| k != KernelKind::Scalar) {
        for scalar in row_scalars(kind) {
            for class in CLASSES {
                let per_size = RULE_SIZES.map(|n| device_times(data, class, kind, scalar, n));
                for device in per_size[0].keys() {
                    let times =
                        [0, 1].map(|i| per_size[i].get(device).cloned().unwrap_or_default());
                    let cells: String = wide
                        .iter()
                        .map(|&v| format!(" {} |", speedups(&times, v)))
                        .collect();
                    let name = data
                        .sweeps
                        .iter()
                        .find(|r| (&r.target, &r.backend) == (&device.0, &device.1))
                        .map_or("", |r| r.device.as_str());
                    writeln!(
                        out,
                        "| {kind:?} | {} | {class:?} | {} {} ({name}) |{cells}",
                        scalar.name(),
                        device.0,
                        device.1
                    )
                    .unwrap();
                }
            }
        }
    }

    out.push_str(
        "\n### Scalar kernels\n\n\
         CPU blocks of `KernelKind::Scalar` (vector size 1), from histogram (u32) and segmented \
         reduce (f64) (ADR-0015, item 7).\n\n",
    );
    out.push_str("| Class | Type | Block | Reason |\n| --- | --- | ---: | --- |\n");
    for class in CLASSES.into_iter().filter(|&c| c != DeviceClass::Gpu) {
        for scalar in scalars_of(KernelKind::Scalar) {
            let choice = decision.choice(class, KernelKind::Scalar, scalar.bytes());
            writeln!(
                out,
                "| {class:?} | {} | {} | {} |",
                scalar.name(),
                block(choice.and_then(|c| c.cpu_block)),
                choice.map_or("", |c| c.reason.as_str()),
            )
            .unwrap();
        }
    }
    out
}

/// `text` with the part between the markers replaced by `generated`; the markers are appended
/// if `text` has none.
///
/// # Errors
///
/// If `text` has a begin marker without an end marker after it.
pub fn splice(text: &str, generated: &str) -> Result<String, String> {
    let block = format!("{BEGIN_MARKER}\n\n{}\n\n{END_MARKER}", generated.trim());
    let Some(begin) = text.find(BEGIN_MARKER) else {
        let sep = if text.is_empty() || text.ends_with("\n\n") {
            ""
        } else if text.ends_with('\n') {
            "\n"
        } else {
            "\n\n"
        };
        return Ok(format!("{text}{sep}{block}\n"));
    };
    let end = text[begin..]
        .find(END_MARKER)
        .ok_or("a BEGIN GENERATED marker without END GENERATED")?
        + begin
        + END_MARKER.len();
    Ok(format!("{}{block}{}", &text[..begin], &text[end..]))
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::decide::decide;

    #[test]
    fn every_family_class_and_type_has_a_row() {
        let data = PerfData::default();
        let text = render(&data, &decide(&data));
        for kind in KINDS.into_iter().filter(|&k| k != KernelKind::Scalar) {
            for class in CLASSES {
                for scalar in row_scalars(kind) {
                    let row = format!("| {kind:?} | {class:?} | {} |", scalar.name());
                    assert!(text.contains(&row), "no row {row}");
                }
            }
        }
        assert!(text.contains("| PullBack | Gpu | f64 | – | – | – | – | 1 | – | – | no kernel"));
        assert!(text.contains("| CpuSimd512 | f64 | 16 KiB | no data |"));
    }

    #[test]
    fn splice_replaces_or_appends_the_generated_part() {
        let once = splice("# Title\n", "table").unwrap();
        assert_eq!(
            once,
            format!("# Title\n\n{BEGIN_MARKER}\n\ntable\n\n{END_MARKER}\n")
        );
        let twice = splice(&format!("{once}\nafter\n"), "new").unwrap();
        assert_eq!(
            twice,
            format!("# Title\n\n{BEGIN_MARKER}\n\nnew\n\n{END_MARKER}\n\nafter\n")
        );
        assert!(splice(BEGIN_MARKER, "x").is_err());
    }
}
