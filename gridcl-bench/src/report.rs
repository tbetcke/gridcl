/// `t` seconds per point in nanoseconds, to three significant digits.
fn ns(t: f64) -> String {
    let v = t * 1e9;
    if v >= 100.0 {
        format!("{v:.0}")
    } else if v >= 10.0 {
        format!("{v:.1}")
    } else {
        format!("{v:.2}")
    }
}

/// Values at the rule sizes, `a / b`.
fn per_size(values: &[f64], show: impl Fn(f64) -> String) -> String {
    values
        .iter()
        .map(|&v| show(v))
        .collect::<Vec<_>>()
        .join(" / ")
}

/// A degree range: `a–b`, or `a–` for the open-ended last one.
fn span(first: u32, last: Option<u32>) -> String {
    match last {
        Some(last) => format!("{first}–{last}"),
        None => format!("{first}–"),
    }
}

/// The class ratio of the chosen strategies over a range, and why they were chosen.
fn range_summary(
    entry: &PolicyEntry,
    first: u32,
    last: Option<u32>,
    strategy: &str,
) -> (String, String) {
    if entry.class == DeviceClass::CpuSimd256 {
        return ("–".to_owned(), "as CpuSimd512".to_owned());
    }
    if entry.choices.is_empty() {
        return ("–".to_owned(), "no data".to_owned());
    }
    let measured = entry.choices.last().map_or(0, |c| c.degree);
    let choices: Vec<&DegreeChoice> = entry
        .choices
        .iter()
        .filter(|c| c.degree >= first && last.is_none_or(|l| c.degree <= l))
        .collect();
    if choices.is_empty() {
        return (
            "–".to_owned(),
            format!("beyond p = {measured}: loops compiles at every degree"),
        );
    }
    if choices.iter().any(|c| c.fit == Fit::Unresolved) {
        return (
            "–".to_owned(),
            "unresolved: neither direct nor loops ran".to_owned(),
        );
    }
    let ratios: Vec<f64> = choices
        .iter()
        .filter_map(|c| c.ratio(strategy))
        .flatten()
        .copied()
        .collect();
    let lo = ratios.iter().copied().fold(f64::INFINITY, f64::min);
    let hi = ratios.iter().copied().fold(0.0, f64::max);
    let ratio = if (hi - lo).abs() < 0.005 {
        format!("{lo:.2}")
    } else {
        format!("{lo:.2}–{hi:.2}")
    };
    let degrees = |pick: &dyn Fn(&DegreeChoice) -> bool| -> Vec<String> {
        choices
            .iter()
            .filter(|c| pick(c))
            .map(|c| c.degree.to_string())
            .collect()
    };
    let mut why = Vec::new();
    let bases: BTreeSet<&str> = choices.iter().map(|c| c.base).collect();
    if bases.contains("loops") {
        let at = degrees(&|c| c.base == "loops");
        why.push(format!("direct not selectable at p = {}", at.join(", ")));
    }
    if choices.iter().all(|c| c.strategy == c.base) {
        if choices.iter().all(|c| {
            c.ratios.len() == 1
                || c.ratios
                    .iter()
                    .all(|(s, r)| *s == c.base || r.iter().any(|&x| x > ADMIT))
        }) {
            why.push("no strategy 10% faster".to_owned());
        } else {
            why.push("the simplest within 3% of the fastest".to_owned());
        }
    } else {
        why.push("at least 10% faster than the baseline".to_owned());
        let closest = degrees(&|c| c.fit == Fit::Closest);
        if closest.is_empty() {
            why.push("within 3% of the fastest".to_owned());
        } else {
            why.push(format!(
                "closest to the fastest at p = {}",
                closest.join(", ")
            ));
        }
    }
    (ratio, why.join("; "))
}

/// The largest compile and load time of `records` (`ok`), with its cell and degree.
fn largest_compile<'a>(records: impl Iterator<Item = &'a DegreeRecord>) -> String {
    records
        .filter(|r| r.status == "ok")
        .max_by(|a, b| a.compile_s.total_cmp(&b.compile_s))
        .map_or("–".to_owned(), |r| {
            format!("{:.1} ({} {})", r.compile_s, r.cell, r.degree)
        })
}

/// The generated tables of `docs/perf/high-order.md`, without the markers.
pub fn render_high_order(data: &HighOrderData, decision: &DegreeDecision) -> String {
    let mut out = String::new();

    out.push_str(
        "### Degree policy\n\n\
         One row per entry of `gridcl-geometry/degree-policy.toml` and degree range. Ratio: the \
         class time of the chosen strategy over the baseline's (`direct`, or `loops` where \
         `direct` is not selectable), over the range's degrees and rule sizes. The last range is \
         open-ended; after a `direct` choice at the highest measured degree it is `loops`, which \
         compiles at every degree (ADR-0042, item 3). CpuSimd256 has CpuSimd512's table.\n\n",
    );
    out.push_str(
        "| Family | Cell | Class | Type | Degrees | Strategy | Ratio | Reason |\n\
         | --- | --- | --- | --- | --- | --- | ---: | --- |\n",
    );
    for family in POLICY_FAMILIES {
        for &cell in cells_of(family) {
            for class in POLICY_CLASSES {
                for (scalar, _) in SCALARS {
                    let entry = decision
                        .entry(class, family, cell, scalar)
                        .expect("an entry per class, family, cell and scalar");
                    for (first, last, strategy) in entry.spans() {
                        let (ratio, why) = range_summary(entry, first, last, strategy);
                        writeln!(
                            out,
                            "| {family} | {cell} | {class:?} | {} | {} | {strategy} | {ratio} | \
                             {why} |",
                            scalar.name(),
                            span(first, last),
                        )
                        .unwrap();
                    }
                }
            }
        }
    }

    out.push_str(
        "\n### Cost per strategy\n\n\
         Per measured class, policy family, cell type, scalar type and degree: the baseline's \
         class time in ns per point and each selectable strategy's class ratio to it, at the \
         rule sizes (10^6 / 10^7 points on Gpu, 10^6 on the CPU classes, ADR-0052); \"–\" where \
         a strategy is not selectable (not measured on every device, not a candidate of the \
         class, ran its fallback `loops`, or on Gpu a failed launch or a compile over 30 s on \
         Locust). \"n.m.; T3\": `direct` not measured on tetrahedra, hexahedra and prisms at \
         p ≥ 5 (ADR-0050), with its cost from T3's baseline (a88ab2a) over this run's baseline. \
         Jacobian sums J, det J and K; PullBack is the pull-back at 9 Newton iterations.\n\n",
    );
    let heads: String = STRATEGIES.iter().map(|s| format!(" {s} |")).collect();
    let rule: String = STRATEGIES.iter().map(|_| " ---: |").collect();
    writeln!(
        out,
        "| Family | Cell | Class | Type | p | Base | ns per point |{heads} Choice | Reason |"
    )
    .unwrap();
    writeln!(
        out,
        "| --- | --- | --- | --- | ---: | --- | ---: |{rule} --- | --- |"
    )
    .unwrap();
    for family in POLICY_FAMILIES {
        for &cell in cells_of(family) {
            for class in MEASURED_CLASSES {
                for (scalar, _) in SCALARS {
                    let entry = decision
                        .entry(class, family, cell, scalar)
                        .expect("an entry");
                    for c in &entry.choices {
                        let cells: String = STRATEGIES
                            .iter()
                            .map(|&s| {
                                let r = match (c.ratio(s), &c.t3_direct) {
                                    (Some(r), _) => per_size(r, |x| format!("{x:.2}")),
                                    (None, Some(t3)) if s == "direct" => {
                                        format!("n.m.; T3: {}", per_size(t3, |x| format!("{x:.2}")))
                                    }
                                    _ => "–".to_owned(),
                                };
                                format!(" {r} |")
                            })
                            .collect();
                        let base_time = if c.base_time.is_empty() {
                            "–".to_owned()
                        } else {
                            per_size(&c.base_time, ns)
                        };
                        writeln!(
                            out,
                            "| {family} | {cell} | {class:?} | {} | {} | {} | {base_time} |{cells} \
                             {} | {} |",
                            scalar.name(),
                            c.degree,
                            c.base,
                            c.strategy,
                            c.reason
                        )
                        .unwrap();
                    }
                }
            }
        }
    }

    out.push_str(
        "\n### Rule 1: p = 8 over p = 4 on tensor cells\n\n\
         The time per point at p = 8 over p = 4 of the strategy the policy selects at p = 8, \
         the geometric mean over the class's devices, at each rule size, against the bounds of \
         ADR-0042 item 1: 3 for the geometric factors and the pull-back's set-up, 1.1 · (9/5)^d \
         for a Newton step (ADR-0049). Step = (t(9) − t(1)) / 8, set-up = t(1) − step. The \
         bounds are reported, not enforced, in M9h; M10 takes them as its target (ADR-0053). \
         Over M9: T3's `direct` time at p = 8 over the strategy's (\"–\" where `direct` has no \
         baseline record, as Locust's hexahedron pull-back at p = 8, which did not compile).\n\n",
    );
    out.push_str(
        "| Class | Type | Cell | Family | Part | Strategy | Points | p = 8 / p = 4 | Bound | Within | Over M9 at p = 8 |\n\
         | --- | --- | --- | --- | --- | --- | ---: | ---: | ---: | --- | ---: |\n",
    );
    for t in tensor_ratios(data, decision) {
        let within = match t.ratio {
            Some(r) if r <= t.bound => "yes",
            Some(_) => "no",
            None => "–",
        };
        writeln!(
            out,
            "| {:?} | {} | {} | {} | {} | {} | 10^{} | {} | {:.2} | {within} | {} |",
            t.class,
            t.scalar.name(),
            t.cell,
            t.family,
            t.part,
            t.strategy,
            t.size.ilog10(),
            t.ratio.map_or("–".to_owned(), |r| format!("{r:.2}")),
            t.bound,
            t.speedup_m9.map_or("–".to_owned(), |r| format!("{r:.1}")),
        )
        .unwrap();
    }

    out.push_str(
        "\n### Rule 11: the policy against `direct` at p ≤ 4\n\n\
         In one paired run per device (the newest), the class ratio of the policy's time over \
         `direct`'s per bench family, cell type, degree p ≤ 4, rule size and pull-back iteration \
         count; the bound is 1.05. A device's ratio is the median over the timed runs of the \
         policy's run i over `direct`'s run i (`degree_sweep --interleave` on CPUs alternates \
         them). CpuSimd128 includes Locust's Grace CPU (ADR-0051).\n\n",
    );
    out.push_str(
        "| Class | Type | Runs | Compared | Missing | Worst policy / direct | At |\n\
         | --- | --- | --- | ---: | ---: | ---: | --- |\n",
    );
    for p in paired_checks(data) {
        let runs: Vec<String> = p
            .runs
            .iter()
            .map(|(t, b, r)| format!("{t} {b} {r}"))
            .collect();
        let (worst, at) = p.worst.as_ref().map_or(("–".to_owned(), "–"), |(r, at)| {
            (format!("{r:.3}"), at.as_str())
        });
        writeln!(
            out,
            "| {:?} | {} | {} | {} | {} | {worst} | {at} |",
            p.class,
            p.scalar.name(),
            if runs.is_empty() {
                "none".to_owned()
            } else {
                runs.join("; ")
            },
            p.compared,
            p.missing,
        )
        .unwrap();
    }

    out.push_str(
        "\n### First-use compile and load times\n\n\
         The largest first-use compile and load time in seconds of each bench family and \
         strategy over cell types, degrees, scalar types and vector sizes, from the launch-only \
         records (rule 6; CUDA with `CUDA_CACHE_DISABLE=1`), with its cell type and degree. Gpu \
         choice: the largest Locust time of the variants the policy selects for the Gpu class \
         (bound 30 s, rule 7).\n\n",
    );
    writeln!(out, "| Target | Backend | Family |{heads} Gpu choice |").unwrap();
    writeln!(out, "| --- | --- | --- |{rule} ---: |").unwrap();
    let launch_devices: BTreeSet<(&str, &str)> = data
        .launch
        .iter()
        .map(|r| (r.target.as_str(), r.backend.as_str()))
        .collect();
    let times = Times::new(data);
    for &(target, backend) in &launch_devices {
        for family in DEGREE_FAMILIES {
            let cells: String = STRATEGIES
                .iter()
                .map(|&s| {
                    let c = largest_compile(data.launch.iter().filter(|r| {
                        r.target == target
                            && r.backend == backend
                            && r.family == family
                            && r.strategy == s
                    }));
                    format!(" {c} |")
                })
                .collect();
            let choice = if (target, backend) == ("locust", "cuda") {
                let mut worst: Option<(f64, String)> = None;
                for &cell in cells_of(family) {
                    for degree in 1..=max_degree(cell) {
                        for (scalar, _) in SCALARS {
                            let s = decision
                                .entry(DeviceClass::Gpu, policy_family(family), cell, scalar)
                                .expect("an entry")
                                .strategy(degree);
                            if let Some(c) = times.locust_compile_s(family, cell, degree, scalar, s)
                                && worst.as_ref().is_none_or(|w| c > w.0)
                            {
                                worst = Some((c, format!("{cell} {degree} {s}")));
                            }
                        }
                    }
                }
                worst.map_or("–".to_owned(), |(c, at)| format!("{c:.1} ({at})"))
            } else {
                "–".to_owned()
            };
            writeln!(out, "| {target} | {backend} | {family} |{cells} {choice} |").unwrap();
        }
    }

    out.push_str(
        "\n### CUDA registers and local memory\n\n\
         Per bench family and strategy on Locust, over cell types, degrees, scalar types and \
         vector sizes (`scripts/bench/cuda-resources.sh`, rule 6): the largest register count, \
         spill and local (stack) bytes per thread, and the smallest maximum of threads per block \
         the register count allows, with the cell type and degree of the largest stack.\n\n",
    );
    out.push_str(
        "| Family | Strategy | Kernels | Registers | Spill bytes | Local bytes | Threads per block | Largest stack at |\n\
         | --- | --- | ---: | ---: | ---: | ---: | ---: | --- |\n",
    );
    for family in DEGREE_FAMILIES {
        for s in STRATEGIES {
            let rows: Vec<&CudaResources> = data
                .resources
                .iter()
                .filter(|r| r.family == family && r.strategy == s)
                .collect();
            if rows.is_empty() {
                continue;
            }
            let regs = rows.iter().map(|r| r.registers).max().unwrap_or(0);
            let spill = rows.iter().map(|r| r.spill_bytes).max().unwrap_or(0);
            let local = rows.iter().max_by_key(|r| r.local_bytes).expect("rows");
            let threads = rows
                .iter()
                .map(|r| r.max_threads_per_block)
                .min()
                .unwrap_or(0);
            writeln!(
                out,
                "| {family} | {s} | {} | {regs} | {spill} | {} | {threads} | {} {} {} |",
                rows.len(),
                local.local_bytes,
                local.cell,
                local.degree,
                local.scalar.name()
            )
            .unwrap();
        }
    }
    out
}

