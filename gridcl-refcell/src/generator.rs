//! The lexicographic sub-entity generator (A.2, A.3; DefElement Convention 2).
//!
//! It derives every sub-entity table from the vertices and the facet planes of a cell:
//! - facets (dimension D_TOP − 1) are the vertex sets of the facet planes;
//! - in three dimensions, edges are the vertex pairs that share at least D_TOP − 1 = 2 facets;
//! - dimension 0 is each vertex, dimension D_TOP the whole cell;
//! - each vertex list is sorted, and each dimension is sorted lexicographically.
//!
//! The `const` tables in `cell.rs` are the source of truth; the unit test below requires this
//! generator to reproduce them for all eight cells.

#![cfg(test)]

use gridcl_dims::CellType;

use crate::{tdim, vertices};

/// The facet planes `n · x = c` of a cell, as (n, c) with three-component normals.
fn facet_planes(cell: CellType) -> Vec<([f64; 3], f64)> {
    let x = [1.0, 0.0, 0.0];
    let y = [0.0, 1.0, 0.0];
    let z = [0.0, 0.0, 1.0];
    let xy = [1.0, 1.0, 0.0];
    let xz = [1.0, 0.0, 1.0];
    let yz = [0.0, 1.0, 1.0];
    let xyz = [1.0, 1.0, 1.0];
    match cell {
        CellType::Point => vec![],
        CellType::Interval => vec![(x, 0.0), (x, 1.0)],
        CellType::Triangle => vec![(x, 0.0), (y, 0.0), (xy, 1.0)],
        CellType::Quadrilateral => vec![(x, 0.0), (x, 1.0), (y, 0.0), (y, 1.0)],
        CellType::Tetrahedron => vec![(x, 0.0), (y, 0.0), (z, 0.0), (xyz, 1.0)],
        CellType::Hexahedron => {
            vec![(x, 0.0), (x, 1.0), (y, 0.0), (y, 1.0), (z, 0.0), (z, 1.0)]
        }
        CellType::Prism => vec![(x, 0.0), (y, 0.0), (xy, 1.0), (z, 0.0), (z, 1.0)],
        CellType::Pyramid => vec![(x, 0.0), (y, 0.0), (z, 0.0), (xz, 1.0), (yz, 1.0)],
    }
}

/// The vertex sets of the facets, each sorted, in the order of `facet_planes`.
fn facets(cell: CellType) -> Vec<Vec<usize>> {
    let verts = vertices(cell);
    facet_planes(cell)
        .into_iter()
        .map(|(n, c)| {
            (0..verts.len())
                .filter(|&v| {
                    let dot: f64 = verts[v].iter().zip(n).map(|(a, b)| a * b).sum();
                    dot == c
                })
                .collect()
        })
        .collect()
}

/// The sub-entities of dimension `dim`, generated by the lexicographic rule.
pub(crate) fn generate(cell: CellType, dim: usize) -> Vec<Vec<usize>> {
    let td = tdim(cell);
    let nv = vertices(cell).len();
    let mut out: Vec<Vec<usize>> = if dim > td {
        vec![]
    } else if dim == 0 {
        (0..nv).map(|v| vec![v]).collect()
    } else if dim == td {
        vec![(0..nv).collect()]
    } else if dim == td - 1 {
        facets(cell)
    } else {
        // dim = 1 in a three-dimensional cell.
        let facets = facets(cell);
        let mut edges = vec![];
        for a in 0..nv {
            for b in a + 1..nv {
                let shared = facets
                    .iter()
                    .filter(|f| f.contains(&a) && f.contains(&b))
                    .count();
                if shared >= td - 1 {
                    edges.push(vec![a, b]);
                }
            }
        }
        edges
    };
    out.sort();
    out
}

#[cfg(test)]
mod tests {
    use super::generate;
    use crate::sub_entities;
    use gridcl_dims::CellType;

    #[test]
    fn generator_reproduces_the_tables() {
        use CellType::*;
        for cell in [
            Point,
            Interval,
            Triangle,
            Quadrilateral,
            Tetrahedron,
            Hexahedron,
            Prism,
            Pyramid,
        ] {
            for dim in 0..=3 {
                let table: Vec<Vec<usize>> =
                    sub_entities(cell, dim).iter().map(|e| e.to_vec()).collect();
                assert_eq!(generate(cell, dim), table, "{cell:?}, dimension {dim}");
            }
        }
    }
}
